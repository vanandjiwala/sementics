import { transpile } from 'sqlingo';
import { DuckDB } from 'sqlingo/duckdb';
import { NODE_CATALOG_BY_KIND } from '../data/nodeCatalog.js';
import { buildStatements } from './pipeline.js';

// Target dialects, loaded lazily so each is its own chunk.
export const DIALECTS = [
  { id: 'spark', label: 'Spark', load: () => import('sqlingo/spark').then((m) => m.Spark) },
  { id: 'databricks', label: 'Databricks', load: () => import('sqlingo/databricks').then((m) => m.Databricks) },
  { id: 'bigquery', label: 'BigQuery', load: () => import('sqlingo/bigquery').then((m) => m.BigQuery) },
  { id: 'snowflake', label: 'Snowflake', load: () => import('sqlingo/snowflake').then((m) => m.Snowflake) },
  { id: 'postgres', label: 'Postgres', load: () => import('sqlingo/postgres').then((m) => m.Postgres) },
  { id: 'redshift', label: 'Redshift', load: () => import('sqlingo/redshift').then((m) => m.Redshift) },
  { id: 'trino', label: 'Trino', load: () => import('sqlingo/trino').then((m) => m.Trino) },
  { id: 'mysql', label: 'MySQL', load: () => import('sqlingo/mysql').then((m) => m.MySQL) },
  { id: 'tsql', label: 'T-SQL', load: () => import('sqlingo/tsql').then((m) => m.TSQL) },
];

const comment = (text) => text.split('\n').map((l) => `-- ${l}`).join('\n');

// Translate the workflow into one script for `Dialect`: sources are existing tables named after
// their nodes, SQL nodes become views, outputs become CREATE TABLE … AS. Node names are left
// unquoted (NAME_RE guarantees plain identifiers) so user queries referencing them still match.
// `schemas` is a dry run's { [nodeId]: [{ name, type }] }, used to document the source tables.
// Returns { sql, warnings: [{ nodeId, message }] }; throws PipelineError on an invalid graph.
export function buildScript(nodes, edges, schemas, Dialect, dialectLabel) {
  const order = buildStatements(nodes, edges).map((s) => nodes.find((n) => n.id === s.nodeId));
  const tr = (sql) => transpile(sql, { read: DuckDB, write: Dialect, pretty: true })[0];
  const categoryOf = (n) => NODE_CATALOG_BY_KIND[n.data.kind].category;
  const warnings = [];

  const header = [
    `-- Generated by Sementics · dialect: ${dialectLabel}`,
    '-- Sources are read from existing tables named after their nodes; unqualified names use the',
    "-- session's default schema/dataset. Translation is best effort: review before running.",
  ].join('\n');

  const sources = [];
  const tableDrops = [];
  const viewDrops = [];
  const creates = [];
  for (const node of order) {
    const { name, config = {} } = node.data;
    const category = categoryOf(node);
    if (category === 'input') {
      const cols = (schemas[node.id] ?? []).map((c) => `"${c.name.replaceAll('"', '""')}" ${c.type}`);
      let ddl = `-- Source ${name} (sample: ${config.path})`;
      if (cols.length) {
        try {
          ddl += ` — expects a table like:\n${comment(tr(`CREATE TABLE ${name} (${cols.join(', ')})`))}`;
        } catch (err) {
          warnings.push({ nodeId: node.id, message: err.message });
          ddl += ` — column types could not be translated; DuckDB types:\n${comment(cols.join(',\n'))}`;
        }
      }
      sources.push(ddl);
    } else if (category === 'output') {
      const input = nodes.find((n) => n.id === edges.find((e) => e.target === node.id).source);
      tableDrops.push(tr(`DROP TABLE IF EXISTS ${name}`));
      creates.push(`-- Output ${name} (sample: ${config.path})\n${tr(`CREATE TABLE ${name} AS SELECT * FROM ${input.data.name}`)}`);
    } else {
      const duckSql = `CREATE VIEW ${name} AS ${config.query.trim().replace(/;\s*$/, '')}`;
      viewDrops.unshift(tr(`DROP VIEW IF EXISTS ${name}`));
      try {
        creates.push(tr(duckSql));
      } catch (err) {
        const message = err.message.split('\n')[0];
        warnings.push({ nodeId: node.id, message });
        creates.push(`-- WARNING: could not translate ${name} (${message}); DuckDB SQL kept as-is\n${duckSql}`);
      }
    }
  }

  // Output tables first, then views in reverse dependency order, so re-runs start clean.
  const statements = [...tableDrops, ...viewDrops, ...creates];
  const sql = [header, ...sources, statements.map((s) => `${s};`).join('\n\n')].join('\n\n');
  return { sql: `${sql}\n`, warnings };
}
