// Self-check: node src/lib/sqlExport.check.mjs
import assert from 'node:assert/strict';
import { Spark } from 'sqlingo/spark';
import { Postgres } from 'sqlingo/postgres';
import { buildScript } from './sqlExport.js';
import { PipelineError } from './pipeline.js';

const node = (id, kind, name, config) => ({ id, data: { kind, name, config } });
const edge = (source, target) => ({ id: `${source}-${target}`, source, target });

const src = node('a', 'csvSource', 'orders', { path: '/tmp/orders.csv' });
const dedup = node('b', 'sql', 'latest', {
  query: 'SELECT id, amount::INTEGER AS amt FROM orders QUALIFY row_number() OVER (PARTITION BY id ORDER BY ts DESC) = 1;',
});
const agg = node('c', 'sql', 'totals', { query: 'SELECT id, sum(amt) AS total FROM latest GROUP BY id' });
const out = node('d', 'csvOutput', 'out_totals', { path: '/tmp/out.csv' });
const nodes = [out, agg, dedup, src];
const edges = [edge('a', 'b'), edge('b', 'c'), edge('c', 'd')];
const schemas = { a: [{ name: 'id', type: 'BIGINT' }, { name: 'amount', type: 'VARCHAR' }, { name: 'ts', type: 'TIMESTAMP' }] };

const spark = buildScript(nodes, edges, schemas, Spark, 'Spark');
assert.deepEqual(spark.warnings, []);
const s = spark.sql;
assert.match(s, /^-- Generated by Sementics · dialect: Spark/);
// Source documented as commented DDL with Spark types.
assert.match(s, /-- Source orders \(sample: \/tmp\/orders\.csv\)/);
assert.match(s, /^-- CREATE TABLE orders \($/m);
assert.match(s, /^-- {3}`amount` STRING,$/m);
// Output table dropped first, then views in reverse dependency order, then creates in order.
const at = (re) => s.search(re);
assert.ok(at(/DROP TABLE IF EXISTS out_totals;/) < at(/DROP VIEW IF EXISTS totals;/));
assert.ok(at(/DROP VIEW IF EXISTS totals;/) < at(/DROP VIEW IF EXISTS latest;/));
assert.ok(at(/DROP VIEW IF EXISTS latest;/) < at(/CREATE VIEW latest AS/));
assert.ok(at(/CREATE VIEW latest AS/) < at(/CREATE VIEW totals AS/));
assert.ok(at(/CREATE VIEW totals AS/) < at(/CREATE TABLE out_totals AS/));
// Translated: QUALIFY rewritten (Spark lacks it), cast mapped, trailing ; stripped.
assert.doesNotMatch(s, /QUALIFY/);
assert.match(s, /CAST\(amount AS INT\)/);
assert.match(s, /-- Output out_totals \(sample: \/tmp\/out\.csv\)\nCREATE TABLE out_totals AS\nSELECT\n {2}\*\nFROM totals;/);
assert.doesNotMatch(s, /;;/);

// Postgres can't CREATE OR REPLACE TABLE, so the script never relies on it.
assert.doesNotMatch(buildScript(nodes, edges, schemas, Postgres, 'Postgres').sql, /OR REPLACE/);

// Untranslatable query: warning on that node, DuckDB SQL kept.
const bad = node('b', 'sql', 'latest', { query: "SELECT strftime(ts, '%Y-%m') AS m FROM orders" });
const r = buildScript([src, bad], [edge('a', 'b')], schemas, Spark, 'Spark');
assert.equal(r.warnings.length, 1);
assert.equal(r.warnings[0].nodeId, 'b');
assert.match(r.sql, /-- WARNING: could not translate latest \(.+\); DuckDB SQL kept as-is\nCREATE VIEW latest AS SELECT strftime/);

// Invalid graph surfaces as PipelineError, like a run would.
assert.throws(() => buildScript([src, out], [], schemas, Spark, 'Spark'), (e) => e instanceof PipelineError && e.nodeId === 'd');

console.log('sqlExport ok');
